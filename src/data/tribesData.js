// Helper to get tribes for a specific state
export const getTribesForState = (stateName) => {
  if (!stateName) return [];
  const stateData = SCHEDULED_TRIBES_BY_STATE.find(
    s => s.state.toLowerCase() === stateName.toLowerCase()
  );
  return stateData ? stateData.tribes : [];
};

// Helper to check if a tribe is PVTG
export const isPVTG = (tribeName) => {
  if (!tribeName) return false;
  return PVTG_LIST.some(
    p => p.name.toLowerCase() === tribeName.toLowerCase() || 
         tribeName.toLowerCase().includes(p.name.toLowerCase())
  );
};
